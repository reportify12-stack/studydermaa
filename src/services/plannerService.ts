// 5. POMODORO SESSION STATS
// ==========================================

export interface PomodoroTodayStats {
  date: string;
  focusSessionsCompleted: number;
  totalFocusMinutes: number;
}

export function getStoredPomodoroStats(): PomodoroTodayStats {
  const today = new Date().toISOString().split('T')[0];
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.POMODORO_STATS);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed.date === today) {
        return parsed;
      }
    }
  } catch {
    // Ignore
  }
  return {
    date: today,
    focusSessionsCompleted: 0,
    totalFocusMinutes: 0,
  };
}

export function incrementPomodoroSession(minutes: number = 25): PomodoroTodayStats {
  const current = getStoredPomodoroStats();
  const updated: PomodoroTodayStats = {
    date: current.date,
    focusSessionsCompleted: current.focusSessionsCompleted + 1,
    totalFocusMinutes: current.totalFocusMinutes + minutes,
  };
  try {
    localStorage.setItem(STORAGE_KEYS.POMODORO_STATS, JSON.stringify(updated));
  } catch {
    // Ignore
  }
  return updated;
}
