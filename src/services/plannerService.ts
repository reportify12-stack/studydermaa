/**
 * Fetches or retrieves the daily motivational quote with the hidden prompt logic.
 * Employs local caching by date to prevent redundant API calls while offering force-refresh.
 */
export async function fetchDailyMotivationQuote(forceRefresh: boolean = false): Promise<DailyMotivation> {
  const todayKey = new Date().toISOString().split('T')[0];

  // 1. Check local cache first unless force refresh requested
  if (!forceRefresh) {
    try {
      const cachedRaw = localStorage.getItem(STORAGE_KEYS.DAILY_QUOTE);
      if (cachedRaw) {
        const cached: DailyMotivation = JSON.parse(cachedRaw);
        if (cached && cached.dateKey === todayKey && cached.quote) {
          return cached;
        }
      }
    } catch {
      // Ignore cache parse errors
    }
  }

  // 2. Fetch fresh quote via server-side Gemini API proxy (/api/gemini/chat)
  try {
    const response = await fetch('/api/gemini/chat', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        messages: [
          {
            role: 'user',
            parts: [{ text: DAILY_MOTIVATION_HIDDEN_PROMPT.userPrompt }],
          },
        ],
        systemInstruction: DAILY_MOTIVATION_HIDDEN_PROMPT.systemInstruction,
        model: 'gemini-3.8-flash',
      }),
    });

    if (response.ok) {
      const data = await response.json();
      const rawText = data?.reply || '';

      if (rawText && typeof rawText === 'string') {
        // Parse the quote and attribution
        let quote = rawText.trim();
        let author = 'Budaya Belajar Positif';

        // Check for delimiter like "—" or "-" or attribution
        const dashIdx = quote.lastIndexOf('—');
        const altDashIdx = quote.lastIndexOf(' - ');

        if (dashIdx !== -1) {
          author = quote.substring(dashIdx + 1).trim();
          quote = quote.substring(0, dashIdx).trim();
        } else if (altDashIdx !== -1) {
          author = quote.substring(altDashIdx + 3).trim();
          quote = quote.substring(0, altDashIdx).trim();
        }

        // Clean quotes wrapping
        quote = quote.replace(/^["'“]/, '').replace(/["'”]$/, '').trim();
        author = author.replace(/^["'“]/, '').replace(/["'”]$/, '').trim();

        // Enforce anti-AI leaks if any model hallucinated
        quote = quote.replace(/as an AI|artificial intelligence|language model|saya sebagai AI/gi, '').trim();

        if (quote.length > 10) {
          const result: DailyMotivation = {
            quote,
            author: author || 'Budaya Belajar Positif',
            category: 'Inspirasi Harian',
            dateKey: todayKey,
          };
          localStorage.setItem(STORAGE_KEYS.DAILY_QUOTE, JSON.stringify(result));
          return result;
        }
      }
    }
  } catch (err) {
    console.warn('AI Quote request encountered network/proxy delay, using curated inspiration:', err);
  }

  // 3. Fallback deterministic selection based on day of month
  const dayOfMonth = new Date().getDate();
  const selectedFallback = FALLBACK_MOTIVATIONAL_QUOTES[dayOfMonth % FALLBACK_MOTIVATIONAL_QUOTES.length];

  const fallbackResult: DailyMotivation = {
    ...selectedFallback,
    dateKey: todayKey,
  };

  try {
    localStorage.setItem(STORAGE_KEYS.DAILY_QUOTE, JSON.stringify(fallbackResult));
  } catch {
    // Ignore storage quota
  }

  return fallbackResult;
}

